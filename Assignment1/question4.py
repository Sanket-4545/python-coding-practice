# Q4. The user enters a string containing a number (e.g."45" ). Convert it to: 
# • a string again 
# • an integer 
# • a float
# Print all three values with their types. 

a = input("Enter the string value:")
print("String:", a, type(a))
print("Integer:", int(a), type(int(a)))
print("Float:", float(a), type(float(a)))

