# Q2. Take two numbers as input from the user and print their sum, difference, 
# product, and quotient. 

a = int(input("Enter the value of a:"))
b = int(input("Enter the value of b:"))

print("The sum of these two number is:" + str(a + b))
print("The difference of these two number is :" + str(a - b))
print("product of these two number is : " + str(a * b))
print("quotient of these two number is :" + str(a / b))
